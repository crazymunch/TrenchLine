/**
 * The SQL a pending migration needs, INCLUDING Prisma's own bookkeeping.
 *
 * `prisma migrate deploy` is the right way to apply a migration and this is
 * not a replacement for it. It exists for the case where the only reachable
 * door to the database is a SQL console — Neon's editor, a psql session
 * somewhere else — because that door has a trap in it.
 *
 * ## The trap
 *
 * Running a migration's DDL by hand changes the schema and tells Prisma
 * nothing. `_prisma_migrations` still says the migration is pending, so the
 * next `migrate deploy` runs it AGAIN, hits "column already exists", and
 * fails — and now the deploy is broken as well as the schema being ahead of
 * the record. A half-applied migration state is worse than an unapplied one
 * because it is not obvious from either side.
 *
 * So this emits the DDL and the `_prisma_migrations` row together, in one
 * transaction. The checksum is the sha256 of the migration file, which is what
 * Prisma stores and what it compares against on the next run — get it wrong
 * and `migrate deploy` reports the migration as MODIFIED, which is a louder
 * failure but still a failure.
 *
 *   node scripts/emit-pending-migration-sql.mjs 20260904224810_user_role_expand [...]
 *
 * With no arguments it lists what is in `prisma/migrations/` and says nothing
 * about what is applied — it has no database connection and does not want one.
 * Compare against `select migration_name from _prisma_migrations` yourself.
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

const DIR = path.resolve(import.meta.dirname, '../prisma/migrations');

const all = fs.readdirSync(DIR)
  .filter((d) => fs.existsSync(path.join(DIR, d, 'migration.sql')))
  .sort();

const wanted = process.argv.slice(2);

if (!wanted.length) {
  console.log('Migrations in prisma/migrations/:\n');
  for (const m of all) console.log(`  ${m}`);
  console.log('\nPass the ones your database has not applied. Check with:');
  console.log('  select migration_name from _prisma_migrations order by started_at;');
  process.exit(0);
}

const unknown = wanted.filter((w) => !all.includes(w));
if (unknown.length) {
  // Loudly: emitting a bookkeeping row for a migration that does not exist
  // would tell the database a lie it cannot detect.
  throw new Error(`No such migration: ${unknown.join(', ')}`);
}

const out = [
  '-- Generated by scripts/emit-pending-migration-sql.mjs',
  '-- Apply in ONE transaction. Each migration is followed by the',
  '-- `_prisma_migrations` row that records it, so the next `prisma migrate',
  '-- deploy` sees it as applied rather than pending.',
  '',
  'BEGIN;',
  '',
];

for (const name of wanted.sort()) {
  const sql = fs.readFileSync(path.join(DIR, name, 'migration.sql'), 'utf8');
  const checksum = crypto.createHash('sha256').update(sql).digest('hex');
  const steps = sql.split(';').filter((s) => s.trim()).length;

  out.push(`-- ---------------------------------------------------------------`);
  out.push(`-- ${name}`);
  out.push(`-- ---------------------------------------------------------------`);
  out.push(sql.trim());
  out.push('');
  out.push('INSERT INTO "_prisma_migrations"');
  out.push('  (id, checksum, migration_name, started_at, finished_at, applied_steps_count)');
  out.push('VALUES');
  out.push(`  (gen_random_uuid()::text, '${checksum}', '${name}', now(), now(), ${steps});`);
  out.push('');
}

out.push('COMMIT;');
out.push('');
out.push('-- Then confirm, from the same console:');
out.push('--   select migration_name, finished_at from _prisma_migrations order by started_at;');

console.log(out.join('\n'));
