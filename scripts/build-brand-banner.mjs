/**
 * The brand lockup: the mark, the wordmark, and nothing else.
 *
 * `bannercode.html` — the delivered original — was drawn with a burnished-gold
 * rim gradient, a steel-plate gradient behind the mark, `rx="2"` corners and a
 * system-sans 900 wordmark. All four are things this app removes: `globals.css`
 * strips every radius and shadow, the design has one border weight and no
 * simulated depth, and the wordmark face is Archivo everywhere else
 * (docs/DESIGN.md). As a raster it rendered unchanged, which is why it survived
 * as long as it did.
 *
 * It also drew its own copy of the mark. Two copies of a logo is how one of
 * them drifts, so this INLINES `public/brand/icon.svg` — the same single source
 * `npm run icons:build` uses — rather than repeating its paths.
 *
 * The icon keeps its own gradients. The Iron Ledger is about the app's chrome;
 * the mark is artwork, and flattening someone's artwork to satisfy a rule about
 * buttons would be reading the rule past its purpose.
 *
 *   node scripts/build-brand-banner.mjs
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';
import { toLines } from './lib/lines.mjs';

const ROOT = path.resolve(import.meta.dirname, '..');
const BRAND = path.join(ROOT, 'public/brand');

/* Fixed brand values, and the same ones `globals.css` defines as `--brand-*`
   and `--bg-base`. Written out because an SVG has no access to CSS tokens. */
const GROUND = '#16181C';   // --bg-base
const HAIRLINE = '#2A2E36'; // --color-border
const GOLD = '#C59B27';     // --brand-gold, and where that token came from
const MUTED = '#7A8290';    // --color-muted

/*
  476, not the original's 680.

  The old banner was a NAV BAR mock — it ran the full width with a status pip
  floating at the far right, and dropping the pip (a green dot reporting
  nothing) left a third of the image empty. This is a lockup, so it is as wide
  as the lockup: 24 of margin, the mark, the gap, the longest line of type, and
  24 again.
*/
const W = 476;
const H = 120;
const MARK = 72;

/**
 * The renderer must actually have Archivo.
 *
 * Loudly, because the failure is silent otherwise: fontconfig substitutes
 * DejaVu Sans without complaint and the banner renders in the wrong face,
 * which is the exact defect this script exists to fix. A wordmark that is
 * quietly the wrong typeface is worse than a build that stops.
 */
function requireFont(family) {
  let got = '';
  try {
    got = execFileSync('fc-match', ['-f', '%{family}', family], { encoding: 'utf8' });
  } catch {
    throw new Error('fontconfig is not available, so the typeface cannot be verified.');
  }
  if (!got.toLowerCase().includes(family.toLowerCase())) {
    throw new Error(
      `"${family}" is not installed — fontconfig offered "${got}" instead.\n`
      + 'Install it before building the banner; a substituted face renders '
      + 'without error and is wrong.',
    );
  }
}

/**
 * `icon.svg`'s drawing content, ready to nest.
 *
 * The `canvas` rect goes: it is the full-bleed dark square the PWA icons need,
 * and the banner draws its own ground. Ids are prefixed because two `<defs>`
 * sharing an id in one document is a silent mis-render — the second definition
 * wins for both.
 */
function markContent() {
  const file = path.join(BRAND, 'icon.svg');
  if (!fs.existsSync(file)) throw new Error(`No mark at ${file}`);

  let svg = fs.readFileSync(file, 'utf8');
  const inner = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>'));

  return inner
    .replace(/\s*<rect\s+id="canvas"[^>]*\/>/, '')
    .replace(/id="([^"]+)"/g, 'id="bn-$1"')
    .replace(/url\(#([^)]+)\)/g, 'url(#bn-$1)');
}

const banner = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}">
  <!--
    Generated by scripts/build-brand-banner.mjs. Edit that, not this.

    Flat: no gradient on the ground, no plate behind the mark, no rim frame, no
    radius, no shadow, and one hairline at one weight. The mark is inlined from
    public/brand/icon.svg so there is one copy of it in the repository.
  -->
  <rect width="${W}" height="${H}" fill="${GROUND}"/>
  <line x1="0" y1="${H - 0.5}" x2="${W}" y2="${H - 0.5}" stroke="${HAIRLINE}" stroke-width="1"/>

  <g transform="translate(24, ${(H - MARK) / 2}) scale(${MARK / 512})">
${toLines(markContent().trim()).map((l) => `    ${l.trim()}`).join('\n')}
  </g>

  <text x="${24 + MARK + 20}" y="62" font-family="Archivo" font-weight="700"
        font-size="38" letter-spacing="4.5" fill="${GOLD}">TRENCHLINE</text>
  <text x="${24 + MARK + 22}" y="86" font-family="IBM Plex Mono" font-weight="400"
        font-size="11" letter-spacing="2.6" fill="${MUTED}">WARBAND TRACKER // CRUSADE COMPANION</text>
</svg>
`;

requireFont('Archivo');
requireFont('IBM Plex Mono');

fs.writeFileSync(path.join(BRAND, 'banner.svg'), banner);

/* 2x, because the README shows it at its CSS size on a retina display. */
const png = await sharp(Buffer.from(banner), { density: 144 })
  .resize({ width: W * 2 })
  .png()
  .toFile(path.join(BRAND, 'banner.png'));

console.log(`banner.svg  ${W}x${H}`);
console.log(`banner.png  ${png.width}x${png.height}  ${(png.size / 1024).toFixed(0)} KB`);
